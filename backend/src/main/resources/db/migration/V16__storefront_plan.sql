-- Тариф витрины: чем платит продавец за её ведение.
--
-- Признак на витрине, а не на учётной записи: витрина у продавца одна, и
-- срок оплаты относится к ней.
--
-- Существующие витрины получают FREE: их заводили до появления тарифов, и
-- списывать за прошлое нельзя.
ALTER TABLE storefronts
    ADD COLUMN plan VARCHAR(16) NOT NULL DEFAULT 'FREE',
    -- Докуда оплачено. Пусто у бесплатного: срок ему не нужен
    ADD COLUMN plan_until TIMESTAMPTZ;

-- Отбор идёт по сроку при проверке просроченных, и по тарифу при показе
-- выделенных витрин в разделе
CREATE INDEX IF NOT EXISTS idx_storefronts_plan
    ON storefronts (plan, plan_until);
