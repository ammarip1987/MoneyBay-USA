-- Тип продавца в объявлении: частное лицо или перепродажа.
--
-- Признак на объявлении, а не на пользователе: один человек продаёт и своё,
-- и купленное для перепродажи, и делить его по учётной записи неверно.
--
-- Прежние объявления получают OWNER: их размещали до появления выбора, и
-- считать их перепродажей нельзя.
ALTER TABLE listings
    ADD COLUMN seller_type VARCHAR(16) NOT NULL DEFAULT 'OWNER';

-- Отбор идёт вместе с разделом и признаком доступности, поэтому указатель
-- составной: по одному seller_type выборка всё равно шла бы через таблицу.
CREATE INDEX idx_listings_seller_type
    ON listings (seller_type, category_id, is_active)
    WHERE is_deleted = false;
