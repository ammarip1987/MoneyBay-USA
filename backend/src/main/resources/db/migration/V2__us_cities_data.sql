INSERT INTO us_city (name, state_code, state_name, population)
SELECT i.name, i.state_code, i.state_name, i.population
FROM us_city_import i
WHERE NOT EXISTS (
    SELECT 1 FROM us_city c WHERE c.name = i.name AND c.state_code = i.state_code
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_us_city_name_state ON us_city (name, state_code);
-- Автоподстановка ищет по префиксу без учёта регистра внутри выбранного штата
CREATE INDEX IF NOT EXISTS ix_us_city_state_lower_name ON us_city (state_code, lower(name));
CREATE INDEX IF NOT EXISTS ix_us_city_state_population ON us_city (state_code, population DESC);
